import 'package:flutter/material.dart';

import 'app.dart';
import 'core/firebase/firebase_initializer.dart';
import 'firebase_options_user.dart';
import 'flavors/flavor.dart';
import 'flavors/flavor_config.dart';

/// Entry point for the USER app ("Depanini", com.depanini.app).
///
/// Run with:
///   flutter run --flavor user \
///     --dart-define-from-file=config/dart_define.json \
///     -t lib/main_user.dart
Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // 1. Resolve flavor configuration before anything else reads it.
  FlavorConfig.initialize(Flavor.user);

  // 2. Initialize Firebase (never throws — see FirebaseInitializer).
  //    Options are generated by `flutterfire configure` and include web.
  final firebaseInit = await FirebaseInitializer.initialize(
    options: DefaultFirebaseOptions.currentPlatform, // from firebase_options_user.dart
  );

  // 3. Run the shared app shell.
  runApp(DepaniniApp(firebaseInit: firebaseInit));
}
